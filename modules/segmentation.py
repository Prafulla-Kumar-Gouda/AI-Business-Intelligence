# SEGMENT INSIGHTS
# ============================================================


def segment_insights(
    summary: pd.DataFrame
) -> list:
    """
    Generate simple business interpretations
    for the detected customer segments.

    Returns a list of dictionaries.
    """

    if summary.empty:
        return []


    insights = []


    for _, row in summary.iterrows():

        segment = row["Segment"]

        customers = int(
            row["Customers"]
        )

        revenue = float(
            row["Revenue"]
        )

        revenue_percentage = float(
            row["Revenue_Percentage"]
        )


        # ====================================================
        # VIP / LOYAL
        # ====================================================

        if (
            segment
            == "VIP / Loyal Customers"
        ):

            insight = (
                f"{customers:,} VIP/Loyal customers "
                f"generate {revenue_percentage:.1f}% "
                f"of customer revenue "
                f"({revenue:,.2f}). "
                "Focus on retention, loyalty benefits, "
                "premium offers and personalised experiences."
            )


        # ====================================================
        # POTENTIAL HIGH VALUE
        # ====================================================

        elif (
            segment
            == "Potential High Value"
        ):

            insight = (
                f"{customers:,} customers are classified "
                "as Potential High Value. "
                "Use cross-selling, personalised offers "
                "and loyalty incentives to increase "
                "their long-term value."
            )


        # ====================================================
        # AT RISK
        # ====================================================

        elif (
            segment
            == "At Risk / Inactive"
        ):

            insight = (
                f"{customers:,} customers are classified "
                "as At Risk / Inactive. "
                "Consider win-back campaigns, personalised "
                "reminders and targeted promotions."
            )


        # ====================================================
        # REGULAR
        # ====================================================

        elif (
            segment
            == "Regular Customers"
        ):

            insight = (
                f"{customers:,} customers belong to the "
                "Regular Customers segment. "
                "Use repeat-purchase campaigns, "
                "cross-selling and loyalty incentives "
                "to move valuable customers into higher "
                "value segments."
            )


        # ====================================================
        # OTHER SEGMENTS
        # ====================================================

        else:

            insight = (
                f"{customers:,} customers belong to "
                f"{segment}. "
                "Review their purchasing behaviour and "
                "target them with appropriate offers."
            )


        insights.append(
            {
                "Segment": segment,
                "Insight": insight,
            }
        )


    return insights