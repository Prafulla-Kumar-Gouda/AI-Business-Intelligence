"""
Universal Customer Segmentation
-------------------------------

Creates customer-level RFM features and segments customers
using K-Means clustering.

RFM:
    Recency
    Frequency
    Monetary Value

The module is designed to work with the Universal AI
Business Intelligence platform and its automatic column
detection system.
"""

import numpy as np
import pandas as pd

from sklearn.cluster import KMeans
from sklearn.preprocessing import StandardScaler


# ============================================================
# BUILD CUSTOMER FEATURES
# ============================================================


def build_customer_features(
    df: pd.DataFrame,
    detected_columns: dict
) -> pd.DataFrame:
    """
    Build customer-level RFM features.

    Features:
        Customer ID
        Recency
        Frequency
        Monetary

    Recency:
        Number of days since the customer's last purchase.

    Frequency:
        Number of unique orders made by the customer.

    Monetary:
        Total revenue generated by the customer.
    """

    if df is None or df.empty:
        return pd.DataFrame()


    # --------------------------------------------------------
    # Detect required business columns
    # --------------------------------------------------------

    customer_column = detected_columns.get(
        "customer_id"
    )

    date_column = detected_columns.get(
        "date"
    )

    order_column = detected_columns.get(
        "order_id"
    )


    # --------------------------------------------------------
    # Customer column is required
    # --------------------------------------------------------

    if (
        not customer_column
        or customer_column not in df.columns
    ):
        return pd.DataFrame()


    data = df.copy()


    # ========================================================
    # REVENUE CALCULATION
    # ========================================================

    quantity_column = detected_columns.get(
        "quantity"
    )

    price_column = detected_columns.get(
        "price"
    )


    if (
        quantity_column
        and quantity_column in data.columns
        and price_column
        and price_column in data.columns
    ):

        quantity = pd.to_numeric(
            data[quantity_column],
            errors="coerce"
        )

        price = pd.to_numeric(
            data[price_column],
            errors="coerce"
        )

        data["__Revenue"] = (
            quantity * price
        )

    elif (
        price_column
        and price_column in data.columns
    ):

        data["__Revenue"] = pd.to_numeric(
            data[price_column],
            errors="coerce"
        )

    elif "Revenue" in data.columns:

        data["__Revenue"] = pd.to_numeric(
            data["Revenue"],
            errors="coerce"
        )

    else:

        data["__Revenue"] = 0.0


    data["__Revenue"] = (
        data["__Revenue"]
        .fillna(0)
    )


    # ========================================================
    # DATE PROCESSING
    # ========================================================

    if (
        date_column
        and date_column in data.columns
    ):

        data["__Date"] = pd.to_datetime(
            data[date_column],
            errors="coerce"
        )

    else:

        data["__Date"] = pd.NaT


    # ========================================================
    # REMOVE INVALID CUSTOMER RECORDS
    # ========================================================

    data = data.dropna(
        subset=[
            customer_column
        ]
    )


    if data.empty:
        return pd.DataFrame()


    # ========================================================
    # REFERENCE DATE
    # ========================================================

    if data["__Date"].notna().any():

        reference_date = (
            data["__Date"].max()
            + pd.Timedelta(days=1)
        )

    else:

        reference_date = (
            pd.Timestamp.today().normalize()
        )


    # ========================================================
    # FREQUENCY
    # ========================================================

    if (
        order_column
        and order_column in data.columns
    ):

        frequency = (
            data.groupby(
                customer_column
            )[order_column]
            .nunique()
        )

    else:

        frequency = (
            data.groupby(
                customer_column
            )
            .size()
        )


    # ========================================================
    # MONETARY VALUE
    # ========================================================

    monetary = (
        data.groupby(
            customer_column
        )["__Revenue"]
        .sum()
    )


    # ========================================================
    # RECENCY
    # ========================================================

    if data["__Date"].notna().any():

        last_purchase = (
            data.groupby(
                customer_column
            )["__Date"]
            .max()
        )

        recency = (
            reference_date
            - last_purchase
        ).dt.days

    else:

        recency = pd.Series(
            0,
            index=frequency.index,
            dtype="int64"
        )


    # ========================================================
    # BUILD CUSTOMER FEATURE TABLE
    # ========================================================

    customer_features = pd.DataFrame(
        {
            "Customer ID": frequency.index,

            "Recency": (
                recency
                .reindex(
                    frequency.index
                )
                .fillna(0)
            ),

            "Frequency": (
                frequency
                .reindex(
                    frequency.index
                )
                .fillna(0)
            ),

            "Monetary": (
                monetary
                .reindex(
                    frequency.index
                )
                .fillna(0)
            ),
        }
    ).reset_index(drop=True)


    # ========================================================
    # NUMERIC SAFETY
    # ========================================================

    customer_features["Recency"] = (
        pd.to_numeric(
            customer_features["Recency"],
            errors="coerce"
        )
        .fillna(0)
        .clip(lower=0)
    )


    customer_features["Frequency"] = (
        pd.to_numeric(
            customer_features["Frequency"],
            errors="coerce"
        )
        .fillna(0)
        .clip(lower=0)
    )


    customer_features["Monetary"] = (
        pd.to_numeric(
            customer_features["Monetary"],
            errors="coerce"
        )
        .fillna(0)
    )


    return customer_features


# ============================================================
# CUSTOMER SEGMENTATION
# ============================================================


def segment_customers(
    df: pd.DataFrame,
    detected_columns: dict,
    n_clusters: int = 4
) -> pd.DataFrame:
    """
    Segment customers using K-Means clustering.

    Default segments:

        1. VIP / Loyal Customers
        2. Potential High Value
        3. Regular Customers
        4. At Risk / Inactive
    """

    customer_features = build_customer_features(
        df,
        detected_columns
    )


    if customer_features.empty:
        return pd.DataFrame()


    # ========================================================
    # DETERMINE NUMBER OF CLUSTERS
    # ========================================================

    customer_count = len(
        customer_features
    )


    if customer_count == 0:
        return pd.DataFrame()


    n_clusters = int(
        max(1, n_clusters)
    )


    if customer_count < n_clusters:

        n_clusters = customer_count


    # ========================================================
    # SINGLE CUSTOMER / SINGLE CLUSTER
    # ========================================================

    if n_clusters == 1:

        customer_features["Cluster"] = 0

        customer_features["Segment"] = (
            "Customers"
        )

        return customer_features


    # ========================================================
    # RFM MODEL DATA
    # ========================================================

    feature_columns = [
        "Recency",
        "Frequency",
        "Monetary"
    ]


    model_data = (
        customer_features[
            feature_columns
        ]
        .copy()
    )


    # ========================================================
    # HANDLE INVALID VALUES
    # ========================================================

    model_data = (
        model_data
        .replace(
            [np.inf, -np.inf],
            np.nan
        )
        .fillna(0)
    )


    # ========================================================
    # ENSURE NON-NEGATIVE VALUES
    # ========================================================

    model_data["Recency"] = (
        model_data["Recency"]
        .clip(lower=0)
    )


    model_data["Frequency"] = (
        model_data["Frequency"]
        .clip(lower=0)
    )


    model_data["Monetary"] = (
        model_data["Monetary"]
        .clip(lower=0)
    )


    # ========================================================
    # LOG TRANSFORMATION
    # ========================================================
    #
    # Retail datasets often contain a few customers with
    # extremely large monetary values.
    #
    # log1p reduces the effect of extreme values and allows
    # K-Means to create more balanced customer groups.
    # ========================================================

    model_data = np.log1p(
        model_data
    )


    # ========================================================
    # STANDARDIZATION
    # ========================================================

    scaler = StandardScaler()

    scaled_features = (
        scaler.fit_transform(
            model_data
        )
    )


    # ========================================================
    # K-MEANS MODEL
    # ========================================================

    model = KMeans(
        n_clusters=n_clusters,
        random_state=42,
        n_init=10
    )


    customer_features["Cluster"] = (
        model.fit_predict(
            scaled_features
        )
    )


    # ========================================================
    # CLUSTER BUSINESS SUMMARY
    # ========================================================

    cluster_summary = (
        customer_features
        .groupby("Cluster")
        .agg(
            Recency=(
                "Recency",
                "mean"
            ),

            Frequency=(
                "Frequency",
                "mean"
            ),

            Monetary=(
                "Monetary",
                "mean"
            ),

            Customers=(
                "Customer ID",
                "count"
            )
        )
    )


    # ========================================================
    # BUSINESS VALUE SCORE
    # ========================================================
    #
    # Lower Recency = better
    # Higher Frequency = better
    # Higher Monetary = better
    #
    # Each component is normalized so that monetary value
    # does not completely dominate the score.
    # ========================================================

    max_recency = max(
        cluster_summary["Recency"].max(),
        1
    )

    max_frequency = max(
        cluster_summary["Frequency"].max(),
        1
    )

    max_monetary = max(
        cluster_summary["Monetary"].max(),
        1
    )


    cluster_summary["BusinessScore"] = (

        (
            1
            - (
                cluster_summary["Recency"]
                / max_recency
            )
        )

        * 40

        +

        (
            cluster_summary["Frequency"]
            / max_frequency
        )

        * 30

        +

        (
            cluster_summary["Monetary"]
            / max_monetary
        )

        * 30

    )


    # ========================================================
    # RANK CLUSTERS
    # ========================================================

    ranked_clusters = (
        cluster_summary[
            "BusinessScore"
        ]
        .sort_values(
            ascending=False
        )
        .index
        .tolist()
    )


    # ========================================================
    # BUSINESS SEGMENT NAMES
    # ========================================================

    segment_names = [

        "VIP / Loyal Customers",

        "Potential High Value",

        "Regular Customers",

        "At Risk / Inactive"

    ]


    cluster_to_segment = {}


    for index, cluster in enumerate(
        ranked_clusters
    ):

        if index < len(
            segment_names
        ):

            cluster_to_segment[
                cluster
            ] = segment_names[index]

        else:

            cluster_to_segment[
                cluster
            ] = (
                f"Customer Segment "
                f"{index + 1}"
            )


    # ========================================================
    # APPLY SEGMENT LABELS
    # ========================================================

    customer_features["Segment"] = (
        customer_features["Cluster"]
        .map(
            cluster_to_segment
        )
        .fillna(
            "Customers"
        )
    )


    return customer_features


# ============================================================
# SEGMENT SUMMARY
# ============================================================


def segment_summary(
    segmented_customers: pd.DataFrame
) -> pd.DataFrame:
    """
    Generate a business summary of customer segments.

    Returns:

        Segment
        Customers
        Revenue
        Revenue_Percentage
        Average_Recency
        Average_Frequency
        Average_Monetary
    """

    if (
        segmented_customers.empty
        or "Segment"
        not in segmented_customers.columns
    ):

        return pd.DataFrame()


    # ========================================================
    # SEGMENT AGGREGATION
    # ========================================================

    summary = (
        segmented_customers
        .groupby(
            "Segment",
            dropna=False
        )
        .agg(

            Customers=(
                "Customer ID",
                "count"
            ),

            Revenue=(
                "Monetary",
                "sum"
            ),

            Average_Recency=(
                "Recency",
                "mean"
            ),

            Average_Frequency=(
                "Frequency",
                "mean"
            ),

            Average_Monetary=(
                "Monetary",
                "mean"
            )

        )
        .reset_index()
    )


    # ========================================================
    # REVENUE PERCENTAGE
    # ========================================================

    total_revenue = (
        summary["Revenue"]
        .sum()
    )


    if total_revenue > 0:

        summary["Revenue_Percentage"] = (
            summary["Revenue"]
            / total_revenue
            * 100
        )

    else:

        summary["Revenue_Percentage"] = 0.0


    # ========================================================
    # ROUND VALUES
    # ========================================================

    summary["Revenue"] = (
        summary["Revenue"]
        .round(2)
    )


    summary["Revenue_Percentage"] = (
        summary["Revenue_Percentage"]
        .round(2)
    )


    summary["Average_Recency"] = (
        summary["Average_Recency"]
        .round(1)
    )


    summary["Average_Frequency"] = (
        summary["Average_Frequency"]
        .round(2)
    )


    summary["Average_Monetary"] = (
        summary["Average_Monetary"]
        .round(2)
    )


    # ========================================================
    # SORT BY REVENUE
    # ========================================================

    summary = (
        summary
        .sort_values(
            "Revenue",
            ascending=False
        )
        .reset_index(drop=True)
    )


    return summary


